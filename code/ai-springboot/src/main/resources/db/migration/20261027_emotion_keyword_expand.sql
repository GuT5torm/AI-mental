-- 迁移：扩充情绪触发关键词，覆盖日常口语化表达
-- 背景：原 12 个词偏书面/重度（失眠、崩溃、绝望），用户说"心情有点糟糕""没睡好"
-- 这类轻量口语时无法命中，导致情绪自动记录不触发
-- 适用：已导入旧版关键词的存量环境（新环境直接导入更新后的 seed.sql，无需本脚本）
-- 幂等：可重复执行，已存在的关键词自动跳过
-- 生效：捕获链路每条消息实时读取关键词表，执行后无需重启服务

INSERT INTO public.emotion_keyword (keyword, enabled)
SELECT v.kw, 1 FROM (VALUES
    ('心情不好'), ('心情糟糕'), ('糟糕'), ('心情很差'), ('不开心'), ('不高兴'),
    ('难过'), ('伤心'), ('郁闷'), ('心烦'), ('好烦'), ('烦死了'),
    ('好累'), ('太累'), ('累死了'), ('疲惫'),
    ('压力'), ('压抑'), ('迷茫'), ('孤独'), ('委屈'), ('心慌'), ('无助'),
    ('低落'), ('沮丧'), ('失落'), ('空虚'),
    ('睡不着'), ('睡不好'), ('没睡好'),
    ('emo')
) AS v(kw)
WHERE NOT EXISTS (SELECT 1 FROM public.emotion_keyword e WHERE e.keyword = v.kw);

