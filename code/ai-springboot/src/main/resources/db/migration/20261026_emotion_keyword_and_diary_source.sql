-- 迁移：情绪触发关键词表 + 情绪日记来源标记
-- 适用：已按旧版 schema.sql 建库的存量环境（新环境直接导入 schema.sql + seed.sql，无需本脚本）
-- 幂等：可重复执行，在已含该表/列的库上为空操作
-- 回退：见文件末尾注释

-- 1. 情绪触发关键词表
CREATE TABLE IF NOT EXISTS public.emotion_keyword (
    id bigint NOT NULL,
    keyword character varying(50) NOT NULL,
    enabled smallint NOT NULL DEFAULT 1,
    created_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(0) without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT emotion_keyword_pkey PRIMARY KEY (id),
    CONSTRAINT emotion_keyword_keyword_key UNIQUE (keyword)
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'public.emotion_keyword'::regclass
          AND attname = 'id' AND attidentity <> ''
    ) THEN
        ALTER TABLE public.emotion_keyword ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
            SEQUENCE NAME public.emotion_keyword_id_seq
            START WITH 1
            INCREMENT BY 1
            NO MINVALUE
            NO MAXVALUE
            CACHE 1
        );
    END IF;
END
$$;

COMMENT ON TABLE public.emotion_keyword IS '情绪触发关键词表';
COMMENT ON COLUMN public.emotion_keyword.id IS '主键ID';
COMMENT ON COLUMN public.emotion_keyword.keyword IS '触发关键词';
COMMENT ON COLUMN public.emotion_keyword.enabled IS '是否启用：1=启用，0=停用';
COMMENT ON COLUMN public.emotion_keyword.created_at IS '创建时间';
COMMENT ON COLUMN public.emotion_keyword.updated_at IS '更新时间';

-- 2. emotion_diary 加来源标记（可空，存量数据不受影响，NULL 视为手动填写）
ALTER TABLE public.emotion_diary ADD COLUMN IF NOT EXISTS source character varying(20);
ALTER TABLE public.emotion_diary ADD COLUMN IF NOT EXISTS source_session_id bigint;

COMMENT ON COLUMN public.emotion_diary.source IS '记录来源：CHAT=AI咨询对话自动记录，MANUAL=手动填写，NULL视为MANUAL';
COMMENT ON COLUMN public.emotion_diary.source_session_id IS 'CHAT来源时关联的咨询会话ID，用于同会话去重与溯源';

-- 3. 预置默认触发词（与 seed.sql 一致；已存在时跳过）
INSERT INTO public.emotion_keyword (keyword, enabled)
SELECT v.kw, 1 FROM (VALUES
    ('焦虑'), ('抑郁'), ('崩溃'), ('难受'), ('压力大'), ('失眠'),
    ('想哭'), ('撑不住'), ('绝望'), ('烦躁'), ('心累'), ('喘不过气')
) AS v(kw)
WHERE NOT EXISTS (SELECT 1 FROM public.emotion_keyword e WHERE e.keyword = v.kw);

